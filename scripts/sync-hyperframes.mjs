/**
 * 同步 hyperframes-motion-library 模板 → 本工作台注册数据
 *
 * 扫描 ../hyperframes-motion-library/templates 下各模板的 index.html，
 * 解析 data-composition-variables 变量声明 + catalog.json 元数据，
 * 生成 src/hyperframes/generated.ts（供 registry 注册使用）。
 *
 * 用法：node scripts/sync-hyperframes.mjs
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const editorRoot = path.resolve(__dirname, '..')
// 源模板库：可配置环境变量 HYPEFRAMES_LIB，默认期望与 animation-editor 平级的 hyperframes-motion-library
const libRoot = process.env.HYPEFRAMES_LIB
  ? path.resolve(process.env.HYPEFRAMES_LIB)
  : path.resolve(editorRoot, '..', 'hyperframes-motion-library')
const templatesRoot = path.join(libRoot, 'templates')
const outFile = path.join(editorRoot, 'src', 'hyperframes', 'generated.ts')

if (!fs.existsSync(path.join(libRoot, 'catalog.json'))) {
  console.error(`未找到源模板库：${libRoot}`)
  console.error('模板已内联进 src/hyperframes/generated.ts，正常运行不需要源目录。')
  console.error('如需更新模板，请先克隆 https://github.com/nutllwhy/hyperframes-motion-library 到该路径，或用 HYPEFRAMES_LIB 指定。')
  process.exit(1)
}

// ---- 1. 读取 catalog.json ----
const catalog = JSON.parse(fs.readFileSync(path.join(libRoot, 'catalog.json'), 'utf-8'))
const catalogMap = new Map(catalog.templates.map((t) => [t.id, t]))

// ---- 2. 扫描模板 ----
const templateDirs = fs
  .readdirSync(templatesRoot, { withFileTypes: true })
  .filter((d) => d.isDirectory())
  .map((d) => d.name)
  .sort()

function parseVariables(html) {
  const m = html.match(/data-composition-variables='([^']*)'/)
  if (!m) return []
  try {
    return JSON.parse(m[1].replace(/&quot;/g, '"').replace(/&#39;/g, "'"))
  } catch {
    return []
  }
}

function mapType(v) {
  switch (v.type) {
    case 'number':
      return { type: 'number', default: Number(v.default ?? 0) }
    case 'color':
      return { type: 'color', default: String(v.default ?? '#FF5A36') }
    case 'enum': {
      const options = (v.options ?? []).map((o) => o.value)
      return { type: 'select', default: String(v.default ?? options[0] ?? ''), options }
    }
    case 'boolean':
      return { type: 'boolean', default: Boolean(v.default) }
    case 'string':
    default:
      return { type: 'text', default: String(v.default ?? '') }
  }
}

const CATEGORY_MAP = {
  数据可视化: '数据',
  知识讲解: '信息',
  透明叠加: '叠加',
}

const defs = []
for (const id of templateDirs) {
  const indexPath = path.join(templatesRoot, id, 'index.html')
  if (!fs.existsSync(indexPath)) continue
  const html = fs.readFileSync(indexPath, 'utf-8')
  const vars = parseVariables(html)
  const meta = catalogMap.get(id)

  // 过滤 hidden（exportMode 等由工作台统一控制），并滤掉纯装饰参数保留全部可编辑内容
  const visibleVars = vars.filter((v) => !v.hidden)
  const schema = visibleVars.map((v) => {
    const base = mapType(v)
    return { key: v.id, label: v.label, ...base }
  })
  const defaultParams = {}
  for (const s of schema) defaultParams[s.key] = s.default

  // 模板动画时长（catalog duration 优先，否则取 index.html data-duration）
  let duration = Number(meta?.duration ?? 5)
  const durMatch = html.match(/data-duration="([\d.]+)"/)
  if (durMatch && !meta?.duration) duration = Number(durMatch[1])

  const rawCategory = meta?.category ?? '知识讲解'
  // 内容卡片选择器：catalog director.frameSelectors 或 subjectSelectors 的并集，
  // 用于"内容提取"——把模板里真正的内容面板放大填满画布（而非整个 1920×1080 缩成小图）
  const frameSelectors = meta?.director?.frameSelectors ?? []
  const subjectSelectors = meta?.director?.subjectSelectors ?? []
  defs.push({
    id,
    name: meta?.name ?? id,
    description: meta?.description ?? '',
    category: CATEGORY_MAP[rawCategory] ?? '信息',
    duration,
    schema,
    defaultParams,
    size: meta?.size ?? '1920×1080',
    // 内联模板 HTML（桥接卡直接用 srcDoc 渲染，不依赖外部目录）
    html: html
      // gsap CDN → 本地 vendor（离线可用）
      .replace(
        /https:\/\/cdn\.jsdelivr\.net\/npm\/gsap@[^/]+\/dist\/gsap\.min\.js/g,
        '/vendor/gsap.min.js',
      ),
    frameSelectors,
    subjectSelectors,
  })
}

// ---- 3. 生成 TS ----
const lines = []
lines.push('// AUTO-GENERATED by scripts/sync-hyperframes.mjs — 不要手改')
lines.push(`// 同步自 hyperframes-motion-library（${catalog.release ?? '?'}，${defs.length} 个模板）`)
lines.push('import type { ParamSchema, Params } from \'../types\'')
lines.push('')
lines.push('export type HyperframesTemplateDef = {')
lines.push('  id: string')
lines.push('  name: string')
lines.push('  description: string')
lines.push('  category: string')
lines.push('  duration: number')
lines.push('  schema: ParamSchema[]')
lines.push('  defaultParams: Params')
lines.push('  size: string')
lines.push('  /** 内联模板 HTML（含本地 gsap 引用，直接用于 srcDoc 渲染） */')
lines.push('  html: string')
lines.push('}')
lines.push('')
lines.push('export const hyperframesTemplates: HyperframesTemplateDef[] = [')
for (const d of defs) {
  lines.push('  {')
  lines.push(`    id: '${d.id}',`)
  lines.push(`    name: ${JSON.stringify(d.name)},`)
  lines.push(`    description: ${JSON.stringify(d.description)},`)
  lines.push(`    category: ${JSON.stringify(d.category)},`)
  lines.push(`    duration: ${d.duration},`)
  lines.push('    schema: [')
  for (const s of d.schema) {
    if (s.type === 'select') {
      lines.push(`      { key: '${s.key}', label: ${JSON.stringify(s.label)}, type: 'select', default: ${JSON.stringify(s.default)}, options: ${JSON.stringify(s.options)} },`)
    } else if (s.type === 'number' || s.type === 'range') {
      lines.push(`      { key: '${s.key}', label: ${JSON.stringify(s.label)}, type: 'number', default: ${JSON.stringify(s.default)} },`)
    } else {
      lines.push(`      { key: '${s.key}', label: ${JSON.stringify(s.label)}, type: '${s.type}', default: ${JSON.stringify(s.default)} },`)
    }
  }
  lines.push('    ],')
  lines.push(`    defaultParams: ${JSON.stringify(d.defaultParams)},`)
  lines.push(`    size: ${JSON.stringify(d.size)},`)
  lines.push(`    html: ${JSON.stringify(d.html)},`)
  lines.push('  },')
}
lines.push(']')
lines.push('')
lines.push(`export const hyperframesTemplateMap = new Map(hyperframesTemplates.map((t) => [t.id, t]))`)
lines.push('')

fs.mkdirSync(path.dirname(outFile), { recursive: true })
fs.writeFileSync(outFile, lines.join('\n'), 'utf-8')
console.log(`✅ 已生成 ${outFile}（${defs.length} 个模板）`)
for (const d of defs) {
  console.log(`  - ${d.id} [${d.category}] ${d.duration}s  schema=${d.schema.length}`)
}
